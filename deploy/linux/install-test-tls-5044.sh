#!/usr/bin/env bash
# HTTPS on port 5044 for Entra testing (https://sh-pp-01:5044/...).
#
# Kestrel must listen ONLY on 127.0.0.1:5044; nginx owns 5044 with TLS.
#
#   sudo bash deploy/linux/install-test-tls-5044.sh
#   sudo bash deploy/linux/install-test-tls-5044.sh --host sh-pp-01.yoursclothing.co.uk
set -euo pipefail

HOST_NAME="$(hostname -s 2>/dev/null || hostname)"
while [[ $# -gt 0 ]]; do
  case "$1" in
    --host) HOST_NAME="${2:?}"; shift 2 ;;
    -h|--help)
      echo "Usage: sudo bash deploy/linux/install-test-tls-5044.sh [--host NAME]"
      exit 0
      ;;
    *) echo "Unknown option: $1" >&2; exit 2 ;;
  esac
done

if [[ "${EUID}" -ne 0 ]]; then
  exec sudo bash "$0" "$@" --host "$HOST_NAME" 2>/dev/null || exec sudo bash "$0" --host "$HOST_NAME"
fi

if ! command -v nginx >/dev/null 2>&1; then
  echo "nginx is required. Run deploy/linux/install-prerequisites.sh first." >&2
  exit 1
fi

TLS_DIR="/etc/leaversform/secrets/tls-5044"
CERT="${TLS_DIR}/test-${HOST_NAME}.crt"
KEY="${TLS_DIR}/test-${HOST_NAME}.key"
NGINX_SITE="/etc/nginx/sites-available/leaversform-5044-ssl"

mkdir -p "$TLS_DIR"
chmod 750 "$TLS_DIR"

if [[ ! -f "$CERT" ]]; then
  echo "Creating self-signed certificate for CN=${HOST_NAME} (365 days)..."
  openssl req -x509 -newkey rsa:2048 -sha256 -days 365 -nodes \
    -keyout "$KEY" \
    -out "$CERT" \
    -subj "/CN=${HOST_NAME}" \
    -addext "subjectAltName=DNS:${HOST_NAME},DNS:localhost"
  chmod 640 "$KEY" "$CERT"
  chown root:root "$KEY" "$CERT"
  echo "Cert: $CERT"
  echo "Install this CA in your PC/browser if you get certificate warnings (expected for self-signed)."
fi

echo "Ensuring leaversform listens on 127.0.0.1:5044 only (nginx uses :5044 for TLS)..."
# shellcheck source=lib/common.sh
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
bash "${ROOT}/deploy/linux/install-systemd.sh" /opt/leaversform/app Development 0

cat > "$NGINX_SITE" <<EOF
# LeaversForm test HTTPS — generated by install-test-tls-5044.sh
server {
    listen 5044;
    listen [::]:5044;
    server_name ${HOST_NAME};
    return 301 https://\$host:5044\$request_uri;
}

server {
    listen 5044 ssl;
    listen [::]:5044 ssl;
    server_name ${HOST_NAME};

    ssl_certificate     ${CERT};
    ssl_certificate_key ${KEY};

    location / {
        proxy_pass http://127.0.0.1:5044;
        proxy_http_version 1.1;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection keep-alive;
        proxy_set_header Host \$host;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto https;
        proxy_cache_bypass \$http_upgrade;
    }
}
EOF

if grep -q 'sites-enabled' /etc/nginx/nginx.conf 2>/dev/null; then
  mkdir -p /etc/nginx/sites-enabled
  ln -sf "$NGINX_SITE" /etc/nginx/sites-enabled/leaversform-5044-ssl
else
  mkdir -p /etc/nginx/conf.d
  cp -f "$NGINX_SITE" /etc/nginx/conf.d/leaversform-5044-ssl.conf
fi

nginx -t
systemctl reload nginx || systemctl restart nginx
systemctl restart leaversform

echo ""
echo "Done. Open: https://${HOST_NAME}:5044/"
echo "Entra redirect URIs (web app, not automation):"
echo "  https://${HOST_NAME}:5044/signin-oidc"
echo "  https://${HOST_NAME}:5044/signout-callback-oidc"
echo "Set LeaversForm:BaseUrl to https://${HOST_NAME}:5044 and restart leaversform after editing JSON."
